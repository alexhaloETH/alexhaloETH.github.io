// skills.js names its pixel icons; this style draws the lucide equivalent.
const PIXEL_TO_LUCIDE = { dungeon: 'grid', wrench: 'wrench' };

export function Icon({ name, className = 'icon' }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[PIXEL_TO_LUCIDE[name] || name]}
    </svg>
  );
}

export function BrandIcon({ name, className = 'brand' }) {
  const icon = BRAND_ICONS[name];
  if (!icon) return null;
  return (
    <svg className={className} viewBox={icon.viewBox} fill="currentColor" aria-hidden="true" focusable="false">
      {icon.paths.map((d) => (
        <path key={d.slice(0, 24)} d={d} />
      ))}
    </svg>
  );
}
