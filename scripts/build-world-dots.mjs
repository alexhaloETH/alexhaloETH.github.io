// Precompute the pixel world map once, so no visitor's browser ever has to.
//
// The old map downloaded a world atlas from a CDN on every visit and ran about 8,000
// point-in-land tests in the browser, again on every resize. The land never moves, so
// this script does those tests once and writes the result to src/data/worldDots.js.
// Places are drawn on top at runtime with plain arithmetic (see WorldMap.jsx).
//
// Only rerun this if you change BOUNDS or STEP:  npm run build:map
// The atlas is world-atlas@2.0.2 land-110m.json (ISC), vendored next to this file so
// builds never touch the network.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

// The part of the world the places span. Equirectangular, so x and y are linear in
// longitude and latitude. Anything you add to places.js must sit inside these bounds.
const BOUNDS = { west: -130, east: 155, north: 72, south: -45 };
const STEP = 5; // degrees per pixel; bigger is chunkier
const UNIT = 10; // viewBox units per degree

const world = JSON.parse(readFileSync(here('./land-110m.json'), 'utf8'));
const land = feature(world, world.objects.land);

const segments = [];
for (let lat = BOUNDS.north - STEP / 2; lat > BOUNDS.south; lat -= STEP) {
  for (let lon = BOUNDS.west + STEP / 2; lon < BOUNDS.east; lon += STEP) {
    if (geoContains(land, [lon, lat])) {
      const x = Math.round((lon - BOUNDS.west) * UNIT);
      const y = Math.round((BOUNDS.north - lat) * UNIT);
      segments.push(`M${x} ${y}h0`);
    }
  }
}

const width = (BOUNDS.east - BOUNDS.west) * UNIT;
const height = (BOUNDS.north - BOUNDS.south) * UNIT;
const source = `// Generated by scripts/build-world-dots.mjs. Do not edit by hand.
// ${segments.length} land pixels, one every ${STEP} degrees.
export const WORLD = ${JSON.stringify({ bounds: BOUNDS, step: STEP, unit: UNIT, width, height }, null, 2)};

export const LAND_PATH =
  '${segments.join('')}';
`;
writeFileSync(here('../src/data/worldDots.js'), source);
console.log(`world map: ${segments.length} pixels, viewBox 0 0 ${width} ${height}`);
